"""Plain-language text generated from the results tables.

Neutral wording throughout: the texts describe what the records show, state
what is unknown, make no accusation and give no legal advice.
"""
from __future__ import annotations

from datetime import datetime, timedelta

EPOCH0 = datetime(2026, 1, 1)

CONVENTION_NOTE = (
    "Money has no physical identity once it is mixed with other funds, so the share of a balance "
    "that is 'disputed' depends on an accounting convention. Two conventions are reported: pro-rata "
    "(every outgoing payment carries the account's current disputed proportion) and first-in-first-out "
    "(the oldest funds leave first). Last-in-first-out (newest funds leave first) is shown only as a "
    "bounding case. These are estimation conventions, not findings about who owns the money."
)

REASON_TEXT = {
    "MISSING_OPENING": "The opening balance of this account is missing from the records.",
    "RECORDS_GAP": "The account's reconstructed closing balance does not match its statement, so records are missing.",
    "UPSTREAM_UNDETERMINABLE": "Funds arrived from an account that cannot be sized, so this account cannot be sized either.",
    "CONVENTIONS_DISAGREE": "The two conventions give different answers; the result is a range.",
    "SKEW_ADJUSTED": "One or more postings were re-ordered because of a small timestamp inconsistency (clock skew).",
    "OVERDRAWN": "The account was overdrawn at some point; funds that repaid the overdraft are treated as absorbed.",
    "NO_DISPUTED_FUNDS_RECEIVED": "The records show no disputed funds reaching this account before the reference time.",
}


def ts(epoch) -> str | None:
    if epoch is None:
        return None
    return (EPOCH0 + timedelta(seconds=int(epoch))).isoformat(timespec="seconds")


def ts_h(epoch) -> str:
    if epoch is None:
        return "an unknown time"
    return (EPOCH0 + timedelta(seconds=int(epoch))).strftime("%d %b %Y, %H:%M")


def inr(x, decimals: bool = True) -> str:
    """Indian digit grouping: 1234567.5 -> ₹12,34,567.50"""
    if x is None:
        return "—"
    x = float(x)
    whole, frac = f"{abs(x):.2f}".split(".")
    if len(whole) > 3:
        head, tail = whole[:-3], whole[-3:]
        groups = []
        while len(head) > 2:
            groups.insert(0, head[-2:])
            head = head[:-2]
        groups.insert(0, head)
        whole = ",".join(groups) + "," + tail
    return ("-" if x < 0 else "") + "₹" + whole + ("." + frac if decimals else "")


def reasons_list(codes: str | None) -> list[str]:
    return [REASON_TEXT.get(c, c) for c in (codes or "").split(";") if c]


def clarification_draft(req: dict, findings: list[dict], case_ref: str) -> str:
    if not findings:
        return ""
    missing = [f for f in findings if f["kind"] == "MISSING"]
    conflicts = [f for f in findings if f["kind"] == "CONFLICT"]
    lines = [
        f"To: {req.get('issuing_officer') or 'The issuing officer'}"
        + (f", {req['designation']}" if req.get("designation") else ""),
        f"{req.get('agency') or 'Issuing agency'}",
        "",
        f"Subject: Clarification needed on account-restriction request no. {req['request_id']}"
        + (f" (case {case_ref})" if case_ref else ""),
        "",
        "We have received the above request. Before any restriction can be applied on the basis of the "
        "available records, the following points need to be clarified:",
        "",
    ]
    n = 1
    for f in missing:
        lines.append(f"{n}. {f['label']}: not stated in the request.")
        n += 1
    for f in conflicts:
        lines.append(f"{n}. {f['detail']}.")
        n += 1
    lines += [
        "",
        "Please send a corrected or supplementary request stating these details. Any restriction is "
        "limited to the amount the records support pending your reply.",
        "",
        "Nodal Officer",
        "(draft generated by TraceHold for review; not sent automatically)",
    ]
    return "\n".join(lines)


def review_reasons(r: dict) -> list[str]:
    cls = r["classification"]
    req, lo, hi = r.get("requested_amount"), r.get("lower_amt"), r.get("upper_amt")
    scope = "the whole balance" if r.get("requested_scope") == "WHOLE_BALANCE" else "an amount"
    out = []
    if cls == "CANNOT_DETERMINE":
        out.append("The records are not sufficient to state a supported range for this account.")
        out += reasons_list(r.get("reason_codes"))
        return out
    out.append(f"Requested {inr(req)} ({scope}); the records support {inr(lo)} to {inr(hi)} "
               f"as traceable to the reported fraud at the reference time.")
    if cls == "WITHIN_EVIDENCE":
        out.append("The requested amount is at or below the lower end of the supported range.")
    elif cls == "WITHIN_RANGE":
        out.append("The requested amount lies inside the range, so the answer depends on the convention chosen.")
    else:
        ratio = r.get("ratio_to_upper")
        if ratio:
            out.append(f"The requested amount is {float(ratio):.2f}× the upper end of the supported range; "
                       f"{inr(r.get('excess_over_upper'))} of it is not traceable to the disputed funds under either convention.")
        else:
            out.append("No disputed funds are traceable to this account, so any restriction exceeds what the records support.")
    return out


def holder_explanation(case: dict, node: dict, request: dict | None) -> str:
    """Neutral explanation for the account holder."""
    acc = node["account_id"]
    paras = []
    if request:
        what = "the whole balance" if node.get("requested_scope") == "WHOLE_BALANCE" else \
            (inr(node.get("requested_amount")) if node.get("requested_amount") is not None else "an amount")
        paras.append(
            f"Your bank received a request from {request.get('agency') or 'a law-enforcement agency'} on "
            f"{ts_h(request.get('received_epoch'))} asking it to restrict {what} in account {acc}. The request "
            f"relates to a reported online fraud (reference {case.get('case_ref')}) in which money was transferred "
            f"on {ts_h(case.get('fraud_epoch'))}.")
    status = node.get("status")
    if status == "UNDETERMINABLE":
        paras.append(
            "The bank's records are not complete enough to say how much, if any, of the reported money is in "
            "your account. No figure is stated for that reason. " + " ".join(reasons_list(node.get("reason_codes"))))
    elif node.get("received") == 0 or (node.get("upper_amt") is not None and float(node["upper_amt"]) < 0.005):
        paras.append("The bank's records do not show any of the reported money remaining in your account at the "
                     "time the request was received.")
    else:
        lo, hi = node.get("lower_amt"), node.get("upper_amt")
        amt = inr(lo) if status == "DETERMINED" else f"between {inr(lo)} and {inr(hi)}"
        paras.append(
            f"Based on the bank's records, {amt} of the balance in your account (which was {inr(node.get('balance_ref'))} "
            f"at that time) can be traced to the reported transfers. The rest of the balance is not traceable "
            f"to them under the methods used.")
        if status == "RANGE":
            paras.append("The figure is a range because money that is mixed with other funds can be attributed in more "
                         "than one reasonable way. The two methods used are explained below.")
    paras.append(CONVENTION_NOTE)
    paras.append(
        "This statement describes what the records show. It does not say that you did anything wrong, and it is not a "
        "decision: any restriction is decided by the authorised officers. It is not legal advice. You may ask your bank "
        "for the details of the request, including the case reference and the issuing officer.")
    return "\n\n".join(paras)


def forwarded_draft(case: dict, request: dict | None, row: dict, institution: str, missing: list[str]) -> str:
    lines = [
        f"To: Nodal Officer, {institution}",
        f"Subject: Request to preserve funds received in account {row['to_acct']} — case {case.get('case_ref')}",
        "",
        f"In connection with reported fraud case {case.get('case_ref')} (reported loss {inr(case.get('loss'))}), "
        f"the records available to us show the following transfer into an account held with you:",
        "",
        f"  Transfer:        {row['txn_id']} (reference {row.get('txn_ref') or 'not recorded'})",
        f"  Time:            {ts_h(row.get('ts_epoch'))}",
        f"  From account:    {row['from_acct']}",
        f"  To account:      {row['to_acct']}",
        f"  Transfer amount: {inr(row.get('amount'))}",
        "",
        "Disputed funds in transit on this transfer, by allocation convention:",
        f"  Pro-rata:  {inr(row.get('carried_pr'))}",
        f"  FIFO:      {inr(row.get('carried_fifo'))}",
        f"  LIFO (bounding case): {inr(row.get('carried_lifo'))}",
        "",
        "Please check your records for this account and size any hold to the disputed amount your records support.",
        "",
        f"Issuing officer: {(request or {}).get('issuing_officer') or '[MISSING]'}, {(request or {}).get('designation') or '[MISSING]'}",
        f"Agency: {(request or {}).get('agency') or '[MISSING]'} — {(request or {}).get('agency_contact') or '[MISSING]'}",
        f"Legal provision: {(request or {}).get('legal_provision') or '[MISSING]'}",
        "",
    ]
    if missing:
        lines.append("Checklist: this draft is INCOMPLETE — missing: " + ", ".join(missing) + ".")
    else:
        lines.append("Checklist: all required items are present.")
    lines.append("(Draft prepared by TraceHold for review and export. It has not been sent.)")
    return "\n".join(lines)
